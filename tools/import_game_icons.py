"""Convert explicitly selected upstream SVG paths into Android VectorDrawable resources.

No downloaded code is executed. Reject unsupported SVG features rather than silently changing shapes.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "art-source/icons/game-icons"
UPSTREAM = BASE / "upstream/icons-master"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)


def resource(path):
    return "gi_" + path.removesuffix(".svg").replace("/", "_").replace("-", "_")


def main():
    selection = json.loads((BASE / "selection.json").read_text())
    archive = BASE / "upstream.zip"
    assert hashlib.sha256(archive.read_bytes()).hexdigest() == selection["archiveSha256"]
    assert zipfile.ZipFile(archive).comment.decode() == selection["revision"]
    paths = sorted(set(selection["glyphs"].values()) | set(selection["items"].values()))
    missing = [path for path in paths if not (UPSTREAM / path).is_file()]
    if missing:
        raise ValueError(f"Missing upstream icons: {missing}")
    output = ROOT / "app/src/main/res/drawable"
    source = BASE / "selected-svg"
    licenses = ROOT / "app/src/main/assets/licenses"
    for directory in (output, source, licenses):
        directory.mkdir(parents=True, exist_ok=True)
    credits = ["Game-icons.net item icons — CC BY 3.0", "Icons made by Lorc and Delapouite.",
        "Lorc: http://lorcblog.blogspot.com", "Delapouite: http://delapouite.com",
        "License: https://creativecommons.org/licenses/by/3.0/",
        "Source: https://github.com/game-icons/icons/tree/" + selection["revision"],
        "Changes: removed black background; converted SVG paths to Android VectorDrawable; runtime recoloring and recipe compositing.",
        "Only the selected SVGs and generated resources are used by the game.\n"]
    records = []
    for path in paths:
        raw = (UPSTREAM / path).read_bytes()
        root = ET.fromstring(raw)
        assert root.attrib.get("viewBox") == "0 0 512 512", path
        vector = ET.Element("vector", {f"{{{ANDROID}}}width": "64dp", f"{{{ANDROID}}}height": "64dp",
            f"{{{ANDROID}}}viewportWidth": "512", f"{{{ANDROID}}}viewportHeight": "512"})
        count = 0
        for element in root:
            tag = element.tag.rsplit("}", 1)[-1]
            if tag == "title":
                continue
            if tag != "path" or "transform" in element.attrib or "style" in element.attrib:
                raise ValueError(f"Unsupported SVG element {path}: {element.attrib}")
            d = element.attrib["d"]
            # Upstream adds a black full-canvas background before the actual white artwork.
            if re.sub(r"\s+", "", d).lower() == "m00h512v512h0z":
                continue
            if element.attrib.get("fill", "#000").lower() not in ("#fff", "#ffffff", "white"):
                raise ValueError(f"Non-white foreground requires explicit review: {path}")
            attrs = {f"{{{ANDROID}}}fillColor": "#FFFFFFFF", f"{{{ANDROID}}}pathData": d}
            if "fill-rule" in element.attrib:
                attrs[f"{{{ANDROID}}}fillType"] = "evenOdd" if element.attrib["fill-rule"] == "evenodd" else "nonZero"
            ET.SubElement(vector, "path", attrs)
            count += 1
        if count == 0:
            raise ValueError(f"No foreground paths: {path}")
        rid = resource(path)
        (output / f"{rid}.xml").write_text(ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8")
        target = source / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(raw)
        author, filename = path.split("/")
        page = f"https://game-icons.net/1x1/{author}/{filename.removesuffix('.svg')}.html"
        credits.append(f"{filename.removesuffix('.svg')} — {'Lorc' if author == 'lorc' else 'Delapouite'}\n{page}\n")
        records.append({"source": path, "resource": rid, "author": author, "url": page, "sha256": hashlib.sha256(raw).hexdigest()})
    (licenses / "game-icons-credits.txt").write_text("\n".join(credits), encoding="utf-8")
    shutil.copyfile(UPSTREAM / "license.txt", licenses / "game-icons-upstream-license.txt")
    (BASE / "import-report.json").write_text(json.dumps(records, indent=2) + "\n", encoding="utf-8")
    lines = ["package com.example.douqiuqiu.ui.components", "", "import com.example.douqiuqiu.R", "",
             "/** Generated by tools/import_game_icons.py; upstream IDs and attribution are preserved. */", "internal object OpenIconResources {",
             "    val glyphs = mapOf("]
    lines += [f"        IconGlyph.{key} to R.drawable.{resource(path)}," for key, path in selection["glyphs"].items()]
    lines += ["    )", "    val items = mapOf("]
    lines += [f'        "{key}" to R.drawable.{resource(path)},' for key, path in selection["items"].items()]
    lines += ["    )", "}", ""]
    (ROOT / "app/src/main/java/com/example/douqiuqiu/ui/components/OpenIconResources.kt").write_text("\n".join(lines), encoding="utf-8")
    print(f"Imported {len(paths)} SVGs, {len(selection['glyphs'])} glyph mappings and {len(selection['items'])} item overrides.")


if __name__ == "__main__":
    main()
